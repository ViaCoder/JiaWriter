// Generate packages/coding-agent/src/writer/data/tgh-chars.ts from the Unicode Unihan database.
// The kTGH field gives each character's position in 通用规范汉字表 (General Standard Chinese
// Characters, 2013): 1-3500 is level 1, 3501-6500 level 2, 6501-8105 level 3.
// Usage: node scripts/writer-gen-tgh.mjs <Unihan_OtherMappings.txt> <output .ts>
// Source: https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip (unzip it first).

// Read the source and write the output.
import { readFileSync, renameSync, writeFileSync } from "node:fs";
// Tell whether this module is the entry point (CLI) or was imported (tests).
import { fileURLToPath } from "node:url";

// Size of the table.
export const TGH_TOTAL = 8105;
// Last position of level 1.
export const LEVEL1_END = 3500;
// Last position of level 2.
export const LEVEL2_END = 6500;

/** Characters of the table in position order, from the text of Unihan_OtherMappings.txt. */
export function parseTgh(text) {
	// Position -> character.
	const byPosition = new Map();
	// One record per line: U+XXXX<TAB>kTGH<TAB>2013:NNNN.
	for (const line of text.split("\n")) {
		// Fields of the line.
		const [code, field, value] = line.trim().split("\t");
		// Only kTGH records.
		if (field !== "kTGH" || !code?.startsWith("U+") || !value) continue;
		// A value may list several editions; keep the 2013 one.
		for (const entry of value.split(" ")) {
			// Edition and position.
			const [year, position] = entry.split(":");
			// Store the 2013 position.
			if (year === "2013") byPosition.set(Number(position), String.fromCodePoint(Number.parseInt(code.slice(2), 16)));
		}
	}
	// Every position from 1 to 8105 must be present exactly once.
	if (byPosition.size !== TGH_TOTAL) throw new Error(`expected ${TGH_TOTAL} kTGH entries, found ${byPosition.size}`);
	// Characters in position order.
	const chars = [];
	// Walk the positions.
	for (let p = 1; p <= TGH_TOTAL; p++) {
		// Character at this position.
		const ch = byPosition.get(p);
		// A gap means a broken source file.
		if (!ch) throw new Error(`kTGH position ${p} is missing`);
		// Keep it.
		chars.push(ch);
	}
	// The ordered table.
	return chars;
}

/** TypeScript module text for the ordered characters. */
export function renderTghModule(chars, sourceDate) {
	// Level strings.
	const level1 = chars.slice(0, LEVEL1_END).join("");
	const level2 = chars.slice(LEVEL1_END, LEVEL2_END).join("");
	const level3 = chars.slice(LEVEL2_END).join("");
	// File text in the layout biome produces (the long strings go on their own indented line).
	return [
		"/**",
		" * 通用规范汉字表 (General Standard Chinese Characters, 2013) in table order.",
		" * Generated by scripts/writer-gen-tgh.mjs from the kTGH field of the Unicode Unihan database",
		` * (Unihan_OtherMappings.txt, ${sourceDate}). Do not edit by hand.`,
		" * Unihan data: Copyright © Unicode, Inc., Unicode License v3, https://www.unicode.org/license.txt",
		" */",
		"",
		"/** Level 1: 3,500 common characters (positions 1-3500). */",
		"export const TGH_LEVEL1 =",
		`\t"${level1}";`,
		"",
		"/** Level 2: 3,000 characters (positions 3501-6500). */",
		"export const TGH_LEVEL2 =",
		`\t"${level2}";`,
		"",
		"/** Level 3: 1,605 specialised characters (positions 6501-8105). */",
		"export const TGH_LEVEL3 =",
		`\t"${level3}";`,
		"",
	].join("\n");
}

/** Date line of the Unihan file ("unknown date" when absent). */
export function sourceDateOf(text) {
	// "# Date: 2026-07-31 00:00:00 GMT [KL]".
	const m = /^# Date: (\d{4}-\d{2}-\d{2})/m.exec(text);
	// The date only.
	return m ? m[1] : "unknown date";
}

// Run as a command only when executed directly, not when imported by tests.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	// Positional arguments.
	const [src, dest] = process.argv.slice(2);
	// Both paths are required.
	if (!src || !dest) {
		// Usage on stderr.
		console.error("usage: node scripts/writer-gen-tgh.mjs <Unihan_OtherMappings.txt> <output .ts>");
		// Exit code 2 marks a usage error.
		process.exit(2);
	}
	// Source text.
	const text = readFileSync(src, "utf-8");
	// Module text.
	const out = renderTghModule(parseTgh(text), sourceDateOf(text));
	// Write next to the destination first, then replace atomically.
	const tmp = `${dest}.tmp-${process.pid}`;
	// Temporary file.
	writeFileSync(tmp, out);
	// Atomic replace.
	renameSync(tmp, dest);
}
