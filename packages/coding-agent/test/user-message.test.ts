import { describe, expect, test } from "vitest";
import { UserMessageComponent } from "../src/modes/interactive/components/user-message.ts";
import { initTheme, theme } from "../src/modes/interactive/theme/theme.ts";
import { stripAnsi } from "../src/utils/ansi.ts";

const OSC133_ZONE_START = "\x1b]133;A\x07";
const OSC133_ZONE_END = "\x1b]133;B\x07";
const OSC133_ZONE_FINAL = "\x1b]133;C\x07";

describe("UserMessageComponent", () => {
	test("keeps user message height stable while moving closing OSC markers off line end", () => {
		initTheme("dark");

		const component = new UserMessageComponent("hello");
		const lines = component.render(20);

		// JiaWriter: one line, no blank rows of its own, behind a bold "> " in the user colour, with no background band.
		expect(lines).toHaveLength(1);
		expect(lines[0].startsWith(OSC133_ZONE_END + OSC133_ZONE_FINAL + OSC133_ZONE_START)).toBe(true);
		expect(stripAnsi(lines[0]).trimEnd()).toBe(" > hello");
		expect(lines[0]).toContain(theme.fg("userMessageText", theme.bold("> ")));
		expect(lines[0]).toContain(theme.fg("userMessageText", "hello"));
		expect(lines[0]).not.toContain("\x1b[4");
	});

	test("chains Markdown transformers with user message context", () => {
		initTheme("dark");
		const calls: string[] = [];
		const component = new UserMessageComponent("The input is $x^2$.", undefined, 1, [
			(markdown, context) => {
				calls.push("formula");
				// JiaWriter: the mark "> " and the padding come off the width.
				expect(context).toEqual({ messageType: "user", isStreaming: false, availableWidth: 77 });
				return markdown.replace("$x^2$", "x²");
			},
			(markdown) => {
				calls.push("suffix");
				return `${markdown} Done.`;
			},
		]);

		expect(stripAnsi(component.render(80).join("\n"))).toContain("The input is x². Done.");
		expect(calls).toEqual(["formula", "suffix"]);
	});

	test("reapplies Markdown transformers when invalidated", () => {
		initTheme("dark");
		let suffix = "before";
		const component = new UserMessageComponent("Message", undefined, 1, [(markdown) => `${markdown} ${suffix}`]);

		expect(stripAnsi(component.render(80).join("\n"))).toContain("Message before");

		suffix = "after";
		component.invalidate();

		expect(stripAnsi(component.render(80).join("\n"))).toContain("Message after");
	});
});
